function oneLineOrder({
  receiptId,
  orderDate,
  customerId,
  customerName,
  phone,
  address,
  area = "",
  serviceType,
  clothesCount,
  totalAmount,
  pickupDate = "",
  deliveryDate = "",
  collectedBy = "",
  deliveredBy = "",
  referralSource = "",
}) {
  const price = clothesCount ? Math.round((Number(totalAmount) / Number(clothesCount)) * 100) / 100 : 0;

  return {
    id: receiptId.toLowerCase(),
    receiptId,
    orderDate,
    customerId: customerId.toLowerCase(),
    customerName,
    phone,
    address,
    area,
    items: [
      {
        id: `${receiptId.toLowerCase()}-item-1`,
        serviceType,
        quantity: clothesCount,
        customerPrice: price,
        dhobiCost: 0,
        lineTotal: totalAmount,
        lineDhobiCost: 0,
        lineProfit: totalAmount,
      },
    ],
    clothesCount,
    totalAmount,
    dhobiCost: 0,
    grossProfit: totalAmount,
    orderStatus: "Delivered",
    paymentStatus: "Done",
    paymentMode: "",
    pickupDate,
    deliveryDate,
    pickupStatus: pickupDate ? "done" : "",
    deliveryStatus: deliveryDate ? "done" : "",
    collectedBy,
    deliveredBy,
    customerNotes: "",
    referralSource,
  };
}

